"""Golden generator for the `gpu_audioseal` suite (raiw-gpu AudioSeal detector).

Run from the repository root with `audioseal==0.2.1` importable, e.g.
`PYTHONPATH=<dir with audioseal, omegaconf, antlr4, einops> .venv/bin/python rs-ai-watermarks/tools/goldens/gpu_audioseal.py`.

Cases: seeded synthetic audio (regenerated by the Rust test), an AudioSeal-marked
signal stored as int16 PCM, an odd-length input, and a tracked video fixture's
audio track decoded in place by ffmpeg.
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[3] / "src"))

from gpu_common import fixture_input, pcm16_b64, strided, synthetic_signal, write  # noqa: E402

from remove_ai_watermarks._internal import audioseal  # noqa: E402

SUITE = "gpu_audioseal"
SR = audioseal.SAMPLE_RATE
MESSAGE = (1, 0, 1, 1, 0, 0, 1, 0, 1, 1, 1, 0, 0, 0, 0, 1)


def reading(detector: object, samples: np.ndarray) -> dict[str, object]:
    import torch

    wav = torch.from_numpy(np.ascontiguousarray(samples, dtype=np.float32)).view(1, 1, -1)
    with audioseal._eager(), torch.no_grad():
        result, message = detector(wav, sample_rate=SR)
    probs = result[0, 1, :].numpy()
    summary = audioseal.read(detector, samples)
    return {
        "probabilities": strided(probs, 256),
        "message": [float(v) for v in message.view(-1).numpy()],
        "mean_detect_prob": summary.mean_detect_prob,
        "frac_above_threshold": summary.frac_above_threshold,
        "bits": list(summary.decoded_bits),
        "label": summary.label,
        "detected": summary.detected,
    }


def main() -> None:
    generator, detector = audioseal.load_pinned_models()
    cases: dict[str, dict[str, object]] = {}

    for name, samples_count, seed in (("synthetic_1s", SR, 7), ("synthetic_odd", 12_345, 3)):
        samples = synthetic_signal(samples_count, SR, seed)
        cases[name] = {"input": {"kind": "synthetic", "samples": samples_count, "sample_rate": SR, "seed": seed}}
        cases[name].update(reading(detector, samples))

    carrier = synthetic_signal(SR, SR, 11)
    marked = audioseal.embed(generator, carrier, MESSAGE)
    payload, quantized = pcm16_b64(marked)
    cases["marked_1s"] = {"input": {"kind": "pcm16", "sample_rate": SR, "message": list(MESSAGE), "pcm16_b64": payload}}
    cases["marked_1s"].update(reading(detector, quantized))

    record, samples = fixture_input("provenance/google-gemini-omni-flash-api.mp4", SR, 1.0, 2.0)
    cases["fixture_gemini_omni"] = {"input": record}
    cases["fixture_gemini_omni"].update(reading(detector, samples))

    write(SUITE, "detector", {"repo": audioseal.HF_REPO, "revision": audioseal.HF_REVISION, "cases": cases})


if __name__ == "__main__":
    main()
