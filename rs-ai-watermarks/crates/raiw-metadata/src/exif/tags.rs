pub const INTEROP: &[TagDef] = &[(1, "InteroperabilityIndex", 2)];

/// The table an IFD's tags are looked up in.
pub const fn table(ifd: Ifd) -> &'static [TagDef] {
    match ifd {
        Ifd::Zeroth | Ifd::First => IMAGE,
        Ifd::Exif => EXIF,
        Ifd::Gps => GPS,
        Ifd::Interop => INTEROP,
    }
}

pub fn lookup(ifd: Ifd, tag: u16) -> Option<&'static TagDef> {
    table(ifd).iter().find(|(number, _, _)| *number == tag)
}
